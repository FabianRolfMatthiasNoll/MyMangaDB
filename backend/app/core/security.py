"""Password hashing and JWT session tokens.

The JWT signing key is resolved at runtime and the application **fails
closed**: there is no built-in default key. A publicly known signing key
lets anybody forge an admin session token offline (GHSA-2223-v44q-q2hc),
so the key is taken from (in order):

1. the ``API_TOKEN`` environment variable (``SECRET_KEY`` is accepted as a
   legacy alias for setups generated by older Taskfile versions),
2. a random key that is generated once and persisted next to the database
   (``<database dir>/.secret_key``).

If neither is available the backend refuses to start instead of falling back
to a guessable value.
"""

import logging
import os
import secrets
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Optional

import jwt
from passlib.context import CryptContext

from backend import config

logger = logging.getLogger(__name__)

# Setup password hashing
pwd_context = CryptContext(schemes=["bcrypt"], deprecated="auto")

ALGORITHM = "HS256"
ACCESS_TOKEN_EXPIRE_MINUTES = 60 * 24 * 7  # 1 week for convenience

# Environment variables that may carry an operator provided signing key.
ENV_KEY_NAMES = ("API_TOKEN", "SECRET_KEY")

# Publicly known values that must never be used as signing key.
INSECURE_KEYS = frozenset(
    {
        "insecure-secret-key",
        "insecure_secret_key",
        "secret",
        "secret-key",
        "secretkey",
        "changeme",
        "change-me",
        "change_me",
        "your-secret-key",
        "your_secret_key",
        "my-secret-key",
        "supersecret",
        "token",
    }
)

# Recommended minimum length for an operator provided signing key.
MIN_SECRET_KEY_LENGTH = 32

# Name of the file that holds the generated signing key.
SECRET_KEY_FILE_NAME = ".secret_key"

# Cached signing key - resolved once per process.
_secret_key: Optional[str] = None


def verify_password(plain_password, hashed_password):
    return pwd_context.verify(plain_password, hashed_password)


def get_password_hash(password):
    return pwd_context.hash(password)


def secret_key_path() -> Path:
    """Location of the persisted signing key.

    It lives next to the database file so it is covered by the same
    backup/volume as the data it protects.
    """
    return Path(config.DATABASE_PATH).parent / SECRET_KEY_FILE_NAME


def reset_secret_key_cache() -> None:
    """Forget the cached signing key (used by the tests)."""
    global _secret_key
    _secret_key = None


def _key_from_environment() -> Optional[str]:
    """Return the signing key configured through the environment, if any."""
    for name in ENV_KEY_NAMES:
        value = os.getenv(name)
        if value and value.strip():
            return value.strip()
    return None


def _reject_insecure_key(key: str, origin: str) -> None:
    """Fail closed if the key is a publicly known value."""
    if key.strip().lower() in INSECURE_KEYS:
        raise RuntimeError(
            f"The JWT signing key from {origin} is a publicly known value and must "
            "not be used - anybody could forge valid admin session tokens. Set "
            "API_TOKEN to a long random secret (e.g. `openssl rand -hex 32`)."
        )


def _read_key_file(path: Path) -> Optional[str]:
    """Read the persisted key.

    Returns ``None`` if the file does not exist. Raises ``RuntimeError`` if
    the file exists but cannot be read.
    """
    for _ in range(10):
        try:
            content = path.read_text(encoding="utf-8").strip()
        except FileNotFoundError:
            return None
        except OSError as exc:
            raise RuntimeError(
                f"Unable to read the JWT signing key from {path}: {exc}. "
                "Set the API_TOKEN environment variable instead."
            ) from exc
        if content:
            return content
        # The file exists but is still empty - another process is most likely
        # writing it right now.
        time.sleep(0.1)
    raise RuntimeError(
        f"The JWT signing key file {path} is empty. Delete it and restart the "
        "backend to generate a new one, or set API_TOKEN explicitly."
    )


def _create_key_file(path: Path, key: str) -> bool:
    """Create the key file exclusively.

    Returns ``True`` if this process created the file, ``False`` if it
    already existed (another process won the race).
    """
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        return False
    except OSError as exc:
        raise RuntimeError(
            f"Unable to create the JWT signing key file {path}: {exc}. "
            "Set the API_TOKEN environment variable instead."
        ) from exc

    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(key)
            handle.flush()
            os.fsync(handle.fileno())
    except OSError as exc:
        try:
            os.unlink(path)
        except OSError:
            pass
        raise RuntimeError(
            f"Unable to write the JWT signing key to {path}: {exc}. "
            "Set the API_TOKEN environment variable instead."
        ) from exc

    _restrict_permissions(path)
    return True


def _restrict_permissions(path: Path) -> None:
    """Make sure the key file is not readable by other users."""
    try:
        os.chmod(path, 0o600)
    except OSError:
        logger.warning("Could not restrict the permissions of %s.", path)


def get_secret_key() -> str:
    """Return the JWT signing key, resolving it on first use."""
    global _secret_key
    if _secret_key is not None:
        return _secret_key

    env_key = _key_from_environment()
    if env_key is not None:
        _reject_insecure_key(env_key, "the environment")
        if len(env_key) < MIN_SECRET_KEY_LENGTH:
            logger.warning(
                "The JWT signing key from the environment is shorter than %d "
                "characters. Use a long random value (e.g. `openssl rand -hex 32`).",
                MIN_SECRET_KEY_LENGTH,
            )
        logger.info("Using the JWT signing key from the environment.")
        _secret_key = env_key
        return _secret_key

    path = secret_key_path()
    stored = _read_key_file(path)
    if stored is None:
        candidate = secrets.token_urlsafe(48)
        if _create_key_file(path, candidate):
            stored = candidate
            logger.warning(
                "API_TOKEN is not set - generated a random JWT signing key and "
                "stored it in %s. Set API_TOKEN explicitly (and share it between "
                "all instances) so that sessions survive restarts and work "
                "across replicas.",
                path,
            )
        else:
            # Another process created the file between our read and our write.
            stored = _read_key_file(path)
            if not stored:
                raise RuntimeError(
                    f"Unable to determine the JWT signing key in {path}. "
                    "Set the API_TOKEN environment variable instead."
                )
    else:
        logger.info("Using the persisted JWT signing key from %s.", path)

    _reject_insecure_key(stored, str(path))
    _secret_key = stored
    return _secret_key


def get_secret_key_source() -> str:
    """Describe where the signing key comes from (never the key itself)."""
    if _key_from_environment() is not None:
        return "environment"
    return str(secret_key_path())


def create_access_token(data: dict, expires_delta: Optional[timedelta] = None):
    to_encode = data.copy()
    if expires_delta:
        expire = datetime.now(timezone.utc) + expires_delta
    else:
        expire = datetime.now(timezone.utc) + timedelta(minutes=15)
    to_encode.update({"exp": expire})
    encoded_jwt = jwt.encode(to_encode, get_secret_key(), algorithm=ALGORITHM)
    return encoded_jwt


def decode_access_token(token: str) -> dict:
    """Decode and verify a session token.

    Raises ``jwt.PyJWTError`` if the token is invalid, expired, not signed
    with the current key or missing the required claims.
    """
    return jwt.decode(
        token,
        get_secret_key(),
        algorithms=[ALGORITHM],
        options={"require": ["exp", "sub"]},
    )
